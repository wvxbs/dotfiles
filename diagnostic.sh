#!/bin/zsh

clear

echo "============================================================"
echo "               MACBOOK AIR M5 DIAGNOSTICO"
echo "============================================================"

echo
echo "### DATA"
date

echo
echo "============================================================"
echo "USUARIOS LOGADOS"
echo "============================================================"

who

echo
echo "============================================================"
echo "PROCESSOS POR USUARIO"
echo "============================================================"

ps -Ao user | sort | uniq -c

echo
echo "============================================================"
echo "TOP CPU"
echo "============================================================"

ps -Ao pid,user,%cpu,%mem,etime,command \
| sort -k3 -nr \
| head -25

echo
echo "============================================================"
echo "TOP MEMORIA"
echo "============================================================"

ps -Ao pid,user,%cpu,%mem,rss,vsz,etime,command \
| sort -k4 -nr \
| head -25

echo
echo "============================================================"
echo "VM STAT"
echo "============================================================"

vm_stat

echo
echo "============================================================"
echo "MEMORY PRESSURE"
echo "============================================================"

memory_pressure

echo
echo "============================================================"
echo "SWAP"
echo "============================================================"

sysctl vm.swapusage

echo
echo "============================================================"
echo "BATTERY"
echo "============================================================"

pmset -g batt

echo
echo "============================================================"
echo "POWER SETTINGS"
echo "============================================================"

pmset -g

echo
echo "============================================================"
echo "THERMAL"
echo "============================================================"

pmset -g therm

echo
echo "============================================================"
echo "TOP ENERGY"
echo "============================================================"

top -l 1 -stats pid,user,cpu,mem,power,time,command | head -40

echo
echo "============================================================"
echo "DISK IO"
echo "============================================================"

iostat -d -w 1 -c 3

echo
echo "============================================================"
echo "PROCESSOS DO CWS"
echo "============================================================"

ps -u cws -o pid,%cpu,%mem,etime,command

echo
echo "============================================================"
echo "PROCESSOS DO USUARIO ATUAL"
echo "============================================================"

ps -u "$USER" -o pid,%cpu,%mem,etime,command

echo
echo "============================================================"
echo "WAKEUPS"
echo "============================================================"

top -l 1 | grep wakeups

echo
echo "============================================================"
echo "GPU"
echo "============================================================"

system_profiler SPDisplaysDataType

echo
echo "============================================================"
echo "ULTIMOS WAKE EVENTS"
echo "============================================================"

pmset -g log | tail -40

echo
echo "============================================================"
echo "FIM"
echo "============================================================"
